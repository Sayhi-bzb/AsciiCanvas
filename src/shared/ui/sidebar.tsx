function SidebarStandard({
  children,
  header,
  icon,
  title,
  footer,
  contentClassName,
  className,
  ...props
}: React.ComponentProps<typeof Sidebar> & {
  header?: React.ReactNode;
  icon?: React.ReactNode;
  title?: string;
  footer?: React.ReactNode;
  contentClassName?: string;
}) {
  const { state, isMobile } = useSidebar();
  const isCollapsed = state === "collapsed" && !isMobile;

  return (
    <Sidebar
      collapsible="icon"
      className={cn("z-40 transition-all duration-200", className)}
      {...props}
    >
      {header ?? (
        <SidebarHeader
          className={cn(
            "flex py-4 transition-all duration-200",
            isCollapsed
              ? "flex-col items-center justify-center gap-y-4"
              : "flex-row items-center justify-between px-4 border-b"
          )}
        >
          <div className="flex items-center gap-2">
            {icon && <div className="shrink-0">{icon}</div>}
            {!isCollapsed && title && (
              <span
                className={cn(
                  rx.panelHeading(),
                  "whitespace-nowrap animate-in fade-in duration-300"
                )}
              >
                {title}
              </span>
            )}
          </div>
          <div
            className={cn(
              "flex items-center gap-2",
              isCollapsed ? "flex-col-reverse" : "flex-row"
            )}
          >
            <SidebarTrigger />
          </div>
        </SidebarHeader>
      )}

      <SidebarContent
        className={cn(
          "gap-2 px-2 py-2 transition-all duration-300",
          isCollapsed ? "opacity-0 pointer-events-none" : "opacity-100",
          contentClassName
        )}
      >
        {children}
      </SidebarContent>

      {footer && (
        <SidebarFooter
          className={cn(
            "p-2 border-t transition-all duration-300",
            isCollapsed && "flex-col items-center gap-y-2 px-0"
          )}
        >
          {footer}
        </SidebarFooter>
      )}
    </Sidebar>
  );
}

